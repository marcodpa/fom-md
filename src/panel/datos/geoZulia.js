// Medio ancho del pasillo que cuenta como puente (calzadas, carril y deriva del GPS).
const PASILLO_PUENTE_KM = 0.1

/** Punto dentro de un polígono [lat, lng] (rayo horizontal; basta para esta escala). */
function dentroDe(poligono, lat, lng) {
  let dentro = false
  for (let i = 0, j = poligono.length - 1; i < poligono.length; j = i++) {
    const [yi, xi] = poligono[i]
    const [yj, xj] = poligono[j]
    if (yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) dentro = !dentro
  }
  return dentro
}

/** Kilómetros entre dos puntos [lat, lng] (aproximación plana: basta para tramos cortos). */
export function kmEntre(a, b) {
  const dy = (b[0] - a[0]) * 110.57
  const dx = (b[1] - a[1]) * 111.32 * Math.cos(((a[0] + b[0]) / 2) * Math.PI / 180)
  return Math.hypot(dx, dy)
}

/** Kilómetros de `p` al tramo a–b. */
function kmAlTramo(p, a, b) {
  const k = Math.cos((p[0] * Math.PI) / 180)
  const [x, y] = [p[1] * k, p[0]]
  const [x1, y1] = [a[1] * k, a[0]]
  const [x2, y2] = [b[1] * k, b[0]]
  const dx = x2 - x1
  const dy = y2 - y1
  const largo = dx * dx + dy * dy
  const t = largo ? Math.min(1, Math.max(0, ((x - x1) * dx + (y - y1) * dy) / largo)) : 0
  return Math.hypot(x - (x1 + t * dx), y - (y1 + t * dy)) * 110.57
}

/** ¿Cae en el lago o en el golfo? */
export function enAgua(lat, lng) {
  return dentroDe(LAGO, lat, lng) || dentroDe(GOLFO, lat, lng)
}

/** ¿Va sobre el puente General Rafael Urdaneta? */
export function sobrePuente(lat, lng) {
  for (let i = 1; i < PUENTE.length; i++) if (kmAlTramo([lat, lng], PUENTE[i - 1], PUENTE[i]) <= PASILLO_PUENTE_KM) return true
  return false
}

/** ¿Está en tierra? El puente cuenta como carretera; un dato sin coordenadas, no. */
export function enTierra(lat, lng) {
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) return false
  return !enAgua(lat, lng) || sobrePuente(lat, lng)
}

