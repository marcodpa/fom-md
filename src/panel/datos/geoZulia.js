function prepararRuta(r) {
  const acumulado = [0]
  for (let i = 1; i < r.puntos.length; i++) acumulado.push(acumulado[i - 1] + kmEntre(r.puntos[i - 1], r.puntos[i]))
  return { ...r, acumulado, largo: acumulado[acumulado.length - 1] }
}
/** Las vías con sus kilómetros acumulados, listas para `puntoEnRuta`. */
export const RUTAS_LISTAS = Object.fromEntries(Object.entries(RUTAS).map(([area, rs]) => [area, rs.map(prepararRuta)]))

/** Punto [lat, lng] de la ruta a `d` km recorridos, de ida y vuelta (al llegar al final, regresa). */
export function puntoEnRuta(ruta, d) {
  const L = ruta.largo
  let s = d % (2 * L)
  if (s < 0) s += 2 * L
  if (s > L) s = 2 * L - s
  const { acumulado, puntos } = ruta
  let i = 1
  while (i < acumulado.length - 1 && acumulado[i] < s) i++
  const tramo = acumulado[i] - acumulado[i - 1] || 1
  const k = Math.min(1, Math.max(0, (s - acumulado[i - 1]) / tramo))
  return [puntos[i - 1][0] + (puntos[i][0] - puntos[i - 1][0]) * k, puntos[i - 1][1] + (puntos[i][1] - puntos[i - 1][1]) * k]
}

/**
 * Kilómetro de la ruta donde una unidad puede quedarse quieta: `d` si ahí hay tierra firme;
 * si cae sobre el puente, el más cercano hacia atrás que ya salió de él. Nadie se para en el puente.
 */
export function kmEnTierraFirme(ruta, d) {
  for (let k = d; k > d - 2 * ruta.largo; k -= 0.1) {
    const [lat, lng] = puntoEnRuta(ruta, k)
    if (!enAgua(lat, lng)) return k
  }
  return d
}

/**
 * Sitio de una unidad dentro de su área a partir de dos sorteos entre 0 y 1: el primero elige la
 * vía y el segundo el punto sobre ella. Si está detenida, nunca queda sobre el puente.
 */
export function sitioEnZona(areaId, azarVia, azarPunto, { detenida = false } = {}) {
  const rutas = RUTAS_LISTAS[areaId] ?? RUTAS_LISTAS['area-1']
  const ruta = rutas[Math.min(rutas.length - 1, Math.floor(azarVia * rutas.length))]
  const km = detenida ? kmEnTierraFirme(ruta, azarPunto * ruta.largo) : azarPunto * ruta.largo
  const [lat, lng] = puntoEnRuta(ruta, km)
  return { lat, lng, km, ruta, via: ruta.via, ciudad: ruta.ciudad }
}
